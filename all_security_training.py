def download_massive_cves(total: int = 500) -> List[Dict]:
    """Download large number of CVEs"""
    print(f"Downloading {total} CVEs from NVD...")
    
    all_cves = []
    keywords = ['sql injection', 'xss', 'command injection', 'buffer overflow', 
                'csrf', 'path traversal', 'injection', 'authentication', 
                'authorization', 'cryptographic', 'deserialization', 'xxe',
                'ssrf', 'race condition', 'memory corruption', 'privilege escalation']
    
    base_url = "https://services.nvd.nist.gov/rest/json/cves/2.0"
    
    for keyword in keywords:
        per_keyword = total // len(keywords)
        try:
            params = {
                'resultsPerPage': per_keyword,
                'startIndex': 0,
                'keywordSearch': keyword
            }
            
            response = requests.get(base_url, params=params, timeout=30)
            response.raise_for_status()
            data = response.json()
            
            cves = data.get('vulnerabilities', [])
            for cve in cves:
                cve_data = cve.get('cve', {})
                cve_id = cve_data.get('id', 'unknown')
                
                all_cves.append({
                    'cve_id': cve_id,
                    'keyword': keyword,
                    'historical': True,
                    'source': 'NVD'
                })
            
            print(f"  ✓ {keyword}: {len(cves)} CVEs")
            
        except Exception as e:
            print(f"  ✗ {keyword}: Error - {e}")
    
    return all_cves


